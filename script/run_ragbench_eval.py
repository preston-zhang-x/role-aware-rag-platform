"""
RAGBench HTML ベースライン用の評価スクリプト。

使い方:
    1. FastAPI サーバーを起動:  uvicorn app.main:app --reload
    2. admin 資格情報を設定:
         - EVAL_ADMIN_USERNAME
         - EVAL_ADMIN_PASSWORD
    3. 別ターミナルで実行:      python script/run_ragbench_eval.py
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import unicodedata
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any

import httpx

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.core.config import get_retrieval_settings

API_BASE_URL = "http://localhost:8000/api/v1"
AUTH_API_URL = f"{API_BASE_URL}/auth/login"
RAG_API_URL = f"{API_BASE_URL}/rag/ask"
MANIFEST_FILE = Path("data/ragbench/emanual/manifest.jsonl")
OUTPUT_DIR = Path("docs")
TIMEOUT_SECONDS = 60.0
EXECUTION_MODE = "admin-only ragbench evaluation"
EXECUTED_AS_ROLE = "admin"
HIT_THRESHOLD = 0.35
_TOKEN_RE = re.compile(r"\w+", flags=re.UNICODE)


def build_default_output_file() -> Path:
    mode = get_retrieval_settings().retrieval_mode
    return OUTPUT_DIR / f"report_ragbench_emanual_{mode}.md"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run RAGBench emanual evaluation.")
    parser.add_argument(
        "--manifest",
        default=str(MANIFEST_FILE),
        help="Manifest file generated by prepare_ragbench_html.py",
    )
    parser.add_argument(
        "--output-file",
        default=str(build_default_output_file()),
        help="Markdown report output path.",
    )
    parser.add_argument(
        "--json-output-file",
        default=None,
        help="Optional JSON summary output path.",
    )
    return parser.parse_args()


def load_manifest_records(path: Path = MANIFEST_FILE) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    with Path(path).open(encoding="utf-8") as file_obj:
        for line in file_obj:
            if line.strip():
                records.append(json.loads(line))
    print(f"📂 {len(records)} 件の RAGBench manifest を読み込みました")
    return records


def get_admin_credentials() -> tuple[str, str]:
    username = os.getenv("EVAL_ADMIN_USERNAME")
    password = os.getenv("EVAL_ADMIN_PASSWORD")

    missing_vars = [
        env_var
        for env_var, value in (
            ("EVAL_ADMIN_USERNAME", username),
            ("EVAL_ADMIN_PASSWORD", password),
        )
        if not value
    ]
    if missing_vars:
        joined = ", ".join(missing_vars)
        raise RuntimeError(
            f"Missing required environment variables: {joined}. "
            "Set them before running script/run_ragbench_eval.py."
        )

    return username, password


def extract_error_detail(response: httpx.Response) -> str:
    try:
        payload = response.json()
    except ValueError:
        return response.text.strip()

    if isinstance(payload, dict):
        detail = payload.get("detail")
        if isinstance(detail, str):
            return detail
    return json.dumps(payload, ensure_ascii=False)


def login_as_admin(username: str, password: str) -> str:
    try:
        response = httpx.post(
            AUTH_API_URL,
            data={"username": username, "password": password},
            timeout=TIMEOUT_SECONDS,
        )
        response.raise_for_status()
    except httpx.ConnectError as exc:
        raise RuntimeError(
            "認証 API に接続できません。uvicorn が起動しているか確認してください。 "
            "起動コマンド: uvicorn app.main:app --reload"
        ) from exc
    except httpx.HTTPStatusError as exc:
        detail = extract_error_detail(exc.response)
        raise RuntimeError(
            f"Admin login failed with HTTP {exc.response.status_code}: {detail}"
        ) from exc

    payload = response.json()
    access_token = payload.get("access_token")
    if not access_token:
        raise RuntimeError("Admin login succeeded but access_token is missing.")

    return access_token


def call_rag_api(question: str, access_token: str) -> dict[str, Any]:
    try:
        response = httpx.post(
            RAG_API_URL,
            json={"question": question},
            headers={"Authorization": f"Bearer {access_token}"},
            timeout=TIMEOUT_SECONDS,
        )
    except httpx.ConnectError as exc:
        raise RuntimeError(
            "RAG API に接続できません。uvicorn が起動しているか確認してください。 "
            "起動コマンド: uvicorn app.main:app --reload"
        ) from exc

    response.raise_for_status()
    return response.json()


def call_rag_api_with_reauth(
    question: str,
    access_token: str,
    *,
    username: str,
    password: str,
) -> tuple[dict[str, Any], str]:
    try:
        return call_rag_api(question, access_token), access_token
    except httpx.HTTPStatusError as exc:
        if exc.response.status_code != 401:
            raise

    print(
        "   🔄 Access token expired. Logging in again and retrying this question once."
    )
    refreshed_token = login_as_admin(username, password)
    return call_rag_api(question, refreshed_token), refreshed_token


def normalize_text(text: str) -> str:
    normalized = unicodedata.normalize("NFKC", text or "").lower()
    normalized = re.sub(r"\s+", " ", normalized)
    return normalized.strip()


def tokenize_text(text: str) -> list[str]:
    normalized = normalize_text(text)
    tokens = _TOKEN_RE.findall(normalized)
    if tokens:
        return tokens
    return [char for char in normalized if not char.isspace()]


def compute_token_f1(answer: str, gold_response: str) -> float:
    answer_tokens = tokenize_text(answer)
    gold_tokens = tokenize_text(gold_response)
    if not answer_tokens or not gold_tokens:
        return 0.0

    answer_counter = Counter(answer_tokens)
    gold_counter = Counter(gold_tokens)
    overlap = sum((answer_counter & gold_counter).values())
    if overlap == 0:
        return 0.0

    precision = overlap / len(answer_tokens)
    recall = overlap / len(gold_tokens)
    return 2 * precision * recall / (precision + recall)


def normalize_source_path(path: str) -> str:
    normalized = (path or "").strip().replace("\\", "/")
    return re.sub(r"/+", "/", normalized)


def evaluate_sources(
    sources: list[dict[str, Any]],
    expected_source_files: list[str],
) -> tuple[bool, float]:
    expected = {
        normalize_source_path(source_file)
        for source_file in expected_source_files
        if source_file
    }
    if not expected:
        return False, 0.0

    returned = {
        normalize_source_path(str(source.get("source_file")))
        for source in sources
        if source.get("source_file") is not None
    }
    matched = expected & returned
    return bool(matched), len(matched) / len(expected)


def truncate_text(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return text[:limit] + "..."


def build_error_breakdown(results: list[dict[str, Any]]) -> dict[str, int]:
    counter = Counter(
        result["error_reason"] for result in results if result["error_reason"]
    )
    return dict(counter)


def build_unique_group_key(result: dict[str, Any]) -> str:
    record_id = str(result.get("id") or "").strip()
    if record_id:
        return f"id:{record_id}"
    return f"question:{normalize_text(str(result.get('question') or ''))}"


def build_unique_results(results: list[dict[str, Any]]) -> list[dict[str, Any]]:
    grouped: dict[str, list[dict[str, Any]]] = {}
    for result in results:
        grouped.setdefault(build_unique_group_key(result), []).append(result)

    unique_results: list[dict[str, Any]] = []
    for group_key, group in grouped.items():
        hit_values = [bool(item.get("hit")) for item in group]
        source_hit_values = [bool(item.get("source_hit")) for item in group]
        first_sources = [
            normalize_source_path(str(item.get("first_source_file") or ""))
            for item in group
        ]
        source_orders = [
            tuple(
                normalize_source_path(str(path))
                for path in item.get("source_files", [])
                if path
            )
            for item in group
        ]
        avg_answer_token_f1 = sum(
            float(item.get("answer_token_f1") or 0.0) for item in group
        ) / len(group)
        avg_source_recall = sum(
            float(item.get("source_recall") or 0.0) for item in group
        ) / len(group)
        avg_latency_ms = sum(
            float(item.get("latency_ms") or 0.0) for item in group
        ) / len(group)
        unique_results.append(
            {
                "group_key": group_key,
                "id": group[0].get("id"),
                "question": group[0].get("question"),
                "runs": len(group),
                "hit_pattern": "".join("T" if hit else "F" for hit in hit_values),
                "source_hit_pattern": "".join(
                    "T" if hit else "F" for hit in source_hit_values
                ),
                "any_hit": any(hit_values),
                "both_hit": all(hit_values),
                "hit_flip": len(set(hit_values)) > 1,
                "source_hit_flip": len(set(source_hit_values)) > 1,
                "first_source_flip": len(set(first_sources)) > 1,
                "source_order_flip": len(set(source_orders)) > 1,
                "avg_answer_token_f1": avg_answer_token_f1,
                "avg_source_recall": avg_source_recall,
                "avg_latency_ms": avg_latency_ms,
            }
        )

    unique_results.sort(
        key=lambda item: (
            str(item.get("id") or ""),
            str(item.get("question") or ""),
        )
    )
    return unique_results


def build_unique_summary(
    results: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    unique_results = build_unique_results(results)
    total = len(unique_results)
    summary = {
        "unique_total": total,
        "unique_any_hit": sum(1 for item in unique_results if item["any_hit"]),
        "unique_both_hit": sum(1 for item in unique_results if item["both_hit"]),
        "mode_internal_hit_flip_count": sum(
            1 for item in unique_results if item["hit_flip"]
        ),
        "mode_internal_source_hit_flip_count": sum(
            1 for item in unique_results if item["source_hit_flip"]
        ),
        "mode_internal_first_source_flip_count": sum(
            1 for item in unique_results if item["first_source_flip"]
        ),
        "mode_internal_source_order_flip_count": sum(
            1 for item in unique_results if item["source_order_flip"]
        ),
        "avg_unique_source_recall": (
            sum(item["avg_source_recall"] for item in unique_results) / total
            if total
            else 0.0
        ),
        "avg_unique_answer_token_f1": (
            sum(item["avg_answer_token_f1"] for item in unique_results) / total
            if total
            else 0.0
        ),
        "avg_unique_latency_ms": (
            sum(item["avg_latency_ms"] for item in unique_results) / total
            if total
            else 0.0
        ),
    }
    return unique_results, summary


def format_source_trace(source_files: list[str]) -> str:
    if not source_files:
        return "-"
    return ", ".join(source_files)


def save_summary_json(summary: dict[str, Any], output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(summary, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def run_eval(manifest_path: Path = MANIFEST_FILE) -> dict[str, Any]:
    username, password = get_admin_credentials()
    access_token = login_as_admin(username, password)
    print("🔐 Admin login succeeded. Running RAGBench evaluation in admin-only mode.")

    records = load_manifest_records(manifest_path)

    results: list[dict[str, Any]] = []
    hit_count = 0
    error_count = 0
    total_source_hit = 0
    total_source_recall = 0.0
    total_answer_f1 = 0.0

    for index, record in enumerate(records, start=1):
        question = record["question"]
        gold_response = record["gold_response"]
        expected_source_files = record["expected_source_files"]

        print(f"\n── [{index}/{len(records)}] Q{record['id']}: {question}")

        try:
            response, access_token = call_rag_api_with_reauth(
                question,
                access_token,
                username=username,
                password=password,
            )
            answer = response.get("answer", "")
            sources = response.get("sources", [])
            metadata = response.get("metadata", {})
            source_hit, source_recall = evaluate_sources(
                sources,
                expected_source_files,
            )
            answer_token_f1 = compute_token_f1(answer, gold_response)
            hit = source_hit and answer_token_f1 >= HIT_THRESHOLD

            if hit:
                hit_count += 1
            if source_hit:
                total_source_hit += 1
            total_source_recall += source_recall
            total_answer_f1 += answer_token_f1

            print(
                f"   {'HIT' if hit else 'MISS'} "
                f"(source_hit={source_hit}, f1={answer_token_f1:.3f})"
            )
            print(f"   回答（先頭100文字）: {truncate_text(answer, 100)}")

            results.append(
                {
                    "id": record["id"],
                    "question": question,
                    "gold_response": gold_response,
                    "expected_source_files": expected_source_files,
                    "executed_as": EXECUTED_AS_ROLE,
                    "answer": answer,
                    "sources_count": len(sources),
                    "source_files": [
                        str(source.get("source_file"))
                        for source in sources
                        if source.get("source_file") is not None
                    ],
                    "first_source_file": (
                        sources[0].get("source_file") if sources else None
                    ),
                    "source_hit": source_hit,
                    "source_recall": source_recall,
                    "answer_token_f1": answer_token_f1,
                    "latency_ms": float(metadata.get("latency_ms", 0.0)),
                    "hit": hit,
                    "error": None,
                    "error_reason": None,
                }
            )

        except httpx.HTTPStatusError as exc:
            error_count += 1
            detail = extract_error_detail(exc.response)
            error_text = f"HTTP {exc.response.status_code}"
            if detail:
                error_text += f": {detail}"

            print(f"   ⚠️ HTTP エラー: {error_text}")
            results.append(
                {
                    "id": record["id"],
                    "question": question,
                    "gold_response": gold_response,
                    "expected_source_files": expected_source_files,
                    "executed_as": EXECUTED_AS_ROLE,
                    "answer": "",
                    "sources_count": 0,
                    "source_files": [],
                    "first_source_file": None,
                    "source_hit": False,
                    "source_recall": 0.0,
                    "answer_token_f1": 0.0,
                    "latency_ms": 0.0,
                    "hit": False,
                    "error": error_text,
                    "error_reason": "http_error",
                }
            )

        except Exception as exc:
            error_count += 1
            print(f"   ⚠️ エラー: {exc}")
            results.append(
                {
                    "id": record["id"],
                    "question": question,
                    "gold_response": gold_response,
                    "expected_source_files": expected_source_files,
                    "executed_as": EXECUTED_AS_ROLE,
                    "answer": "",
                    "sources_count": 0,
                    "source_files": [],
                    "first_source_file": None,
                    "source_hit": False,
                    "source_recall": 0.0,
                    "answer_token_f1": 0.0,
                    "latency_ms": 0.0,
                    "hit": False,
                    "error": str(exc),
                    "error_reason": "unexpected_error",
                }
            )

    total = len(records)
    unique_results, unique_summary = build_unique_summary(results)
    summary = {
        "total": total,
        "hit": hit_count,
        "miss": total - hit_count - error_count,
        "error": error_count,
        "accuracy": (hit_count / total * 100) if total else 0.0,
        "source_hit_rate": (total_source_hit / total * 100) if total else 0.0,
        "avg_source_recall": (total_source_recall / total) if total else 0.0,
        "avg_answer_token_f1": (total_answer_f1 / total) if total else 0.0,
        "execution_mode": EXECUTION_MODE,
        "executed_as": EXECUTED_AS_ROLE,
        "results": results,
        "unique_results": unique_results,
        "unique_summary": unique_summary,
        "error_breakdown": build_error_breakdown(results),
        "retrieval_mode": get_retrieval_settings().retrieval_mode,
    }

    print(f"\n{'=' * 60}")
    print(f"RAGBench 結果: {hit_count}/{total} = {summary['accuracy']:.1f}%")
    print(
        "   "
        f"source_hit_rate={summary['source_hit_rate']:.1f}% "
        f"avg_source_recall={summary['avg_source_recall']:.3f} "
        f"avg_answer_token_f1={summary['avg_answer_token_f1']:.3f}"
    )
    print(
        "   "
        f"unique_any_hit={unique_summary['unique_any_hit']}/"
        f"{unique_summary['unique_total']} "
        f"unique_both_hit={unique_summary['unique_both_hit']}/"
        f"{unique_summary['unique_total']} "
        f"hit_flip={unique_summary['mode_internal_hit_flip_count']}"
    )

    return summary


